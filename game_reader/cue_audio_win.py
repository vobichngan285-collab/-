"""Independent low-latency PCM cue playback using the Windows waveOut device.

Unlike winsound.PlaySound, waveOut is independent of the Luna WAV player's
PlaySound channel: a success ding must not cancel or be canceled by reading.
This runs only in CuePlayer's background thread, never on the Tk/OCR thread.
"""
from __future__ import annotations

import ctypes
import io
import time
import wave

WAVE_MAPPER = 0xFFFFFFFF
WAVE_FORMAT_PCM = 1
WHDR_DONE = 0x00000001


class WAVEFORMATEX(ctypes.Structure):
    _fields_ = [
        ("wFormatTag", ctypes.c_ushort),
        ("nChannels", ctypes.c_ushort),
        ("nSamplesPerSec", ctypes.c_uint32),
        ("nAvgBytesPerSec", ctypes.c_uint32),
        ("nBlockAlign", ctypes.c_ushort),
        ("wBitsPerSample", ctypes.c_ushort),
        ("cbSize", ctypes.c_ushort),
    ]


class WAVEHDR(ctypes.Structure):
    _fields_ = [
        ("lpData", ctypes.c_void_p),
        ("dwBufferLength", ctypes.c_uint32),
        ("dwBytesRecorded", ctypes.c_uint32),
        ("dwUser", ctypes.c_size_t),
        ("dwFlags", ctypes.c_uint32),
        ("dwLoops", ctypes.c_uint32),
        ("lpNext", ctypes.c_void_p),
        ("reserved", ctypes.c_size_t),
    ]


def decode_cue(wav_data: bytes) -> tuple[bytes, int]:
    """Accept only bounded mono/16-bit PCM WAV generated by this application."""
    if not isinstance(wav_data, bytes) or len(wav_data) > 512 * 1024:
        raise ValueError("invalid_cue_data")
    with wave.open(io.BytesIO(wav_data), "rb") as source:
        rate = source.getframerate()
        if (source.getnchannels() != 1 or source.getsampwidth() != 2
                or source.getcomptype() != "NONE" or not 8000 <= rate <= 48000
                or source.getnframes() > rate):
            raise ValueError("unsupported_cue_pcm")
        pcm = source.readframes(source.getnframes())
    if not pcm or len(pcm) % 2:
        raise ValueError("empty_cue_pcm")
    return pcm, rate


def play_cue(wav_data: bytes) -> None:
    """Play without touching any winsound/MediaPlayer TTS instance.

    The PCM allocation and WAVEHDR live until the driver marks WHDR_DONE.
    On a device timeout, reset before releasing these buffers.
    """
    pcm, rate = decode_cue(wav_data)
    winmm = ctypes.WinDLL("winmm", use_last_error=True)
    winmm.waveOutOpen.argtypes = [ctypes.POINTER(ctypes.c_void_p), ctypes.c_uint,
                                 ctypes.POINTER(WAVEFORMATEX), ctypes.c_size_t,
                                 ctypes.c_size_t, ctypes.c_uint]
    winmm.waveOutOpen.restype = ctypes.c_uint
    for name in ("waveOutPrepareHeader", "waveOutWrite", "waveOutUnprepareHeader"):
        fn = getattr(winmm, name)
        fn.argtypes = [ctypes.c_void_p, ctypes.POINTER(WAVEHDR), ctypes.c_uint]
        fn.restype = ctypes.c_uint
    winmm.waveOutReset.argtypes = [ctypes.c_void_p]
    winmm.waveOutReset.restype = ctypes.c_uint
    winmm.waveOutClose.argtypes = [ctypes.c_void_p]
    winmm.waveOutClose.restype = ctypes.c_uint

    fmt = WAVEFORMATEX(WAVE_FORMAT_PCM, 1, rate, rate * 2, 2, 16, 0)
    handle = ctypes.c_void_p()
    status = winmm.waveOutOpen(ctypes.byref(handle), WAVE_MAPPER,
                               ctypes.byref(fmt), 0, 0, 0)
    if status != 0:
        raise OSError(f"waveOutOpen_failed_{status}")
    buffer = ctypes.create_string_buffer(pcm)
    hdr = WAVEHDR(ctypes.cast(buffer, ctypes.c_void_p), len(pcm),
                  0, 0, 0, 0, None, 0)
    prepared = False
    try:
        status = winmm.waveOutPrepareHeader(handle, ctypes.byref(hdr), ctypes.sizeof(hdr))
        if status != 0:
            raise OSError(f"waveOutPrepareHeader_failed_{status}")
        prepared = True
        status = winmm.waveOutWrite(handle, ctypes.byref(hdr), ctypes.sizeof(hdr))
        if status != 0:
            raise OSError(f"waveOutWrite_failed_{status}")
        deadline = time.monotonic() + len(pcm) / (rate * 2) + 1.0
        while not (hdr.dwFlags & WHDR_DONE):
            if time.monotonic() >= deadline:
                winmm.waveOutReset(handle)
                raise TimeoutError("waveOut_playback_timeout")
            time.sleep(0.008)
    finally:
        # A reset guarantees the device no longer references our buffers.
        if prepared and not (hdr.dwFlags & WHDR_DONE):
            winmm.waveOutReset(handle)
        if prepared:
            winmm.waveOutUnprepareHeader(handle, ctypes.byref(hdr), ctypes.sizeof(hdr))
        winmm.waveOutClose(handle)
